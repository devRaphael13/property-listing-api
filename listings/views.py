"""API views for listings.

The OpenAPI schema is generated by drf-spectacular from the serializers and the
`extend_schema` annotations below, so `/api/docs/` stays in step with the code.
"""

from django.utils.decorators import method_decorator
from django.views.decorators.cache import never_cache
from drf_spectacular.types import OpenApiTypes
from drf_spectacular.utils import (
    OpenApiExample,
    OpenApiResponse,
    extend_schema,
    extend_schema_view,
)
from rest_framework import viewsets
from rest_framework.decorators import action
from rest_framework.response import Response
from rest_framework.views import APIView

from listings.filters import apply_exact_bedrooms, apply_filters, order_queryset, rank_by_distance
from listings.models import Listing
from listings.pagination import ListingPagination
from listings.serializers import (
    ErrorEnvelopeSerializer,
    ListingSerializer,
    SearchQuerySerializer,
    SearchResultSerializer,
)

ERRORS = {
    400: OpenApiResponse(ErrorEnvelopeSerializer, description="Validation or malformed request."),
    404: OpenApiResponse(ErrorEnvelopeSerializer, description="Not found."),
    405: OpenApiResponse(ErrorEnvelopeSerializer, description="Method not allowed."),
}

LISTING_EXAMPLE = OpenApiExample(
    "Semi-detached house for sale",
    value={
        "title": "3 Bedroom Terraced House for Sale in Lekki",
        "description": "Estate in a gated community, BOQ completed, title and docs ready.",
        "price": "145000000.00",
        "type": "sale",
        "bedrooms": 3,
        "agent_id": "agent-004",
        "location": {"name": "Lekki", "lat": 6.44, "lng": 3.47},
    },
    request_only=True,
)


@extend_schema_view(
    list=extend_schema(
        summary="List listings",
        description="Newest first. Use `/api/listings/search/` to filter by price, "
        "bedrooms, type or distance.",
        responses={200: ListingSerializer(many=True), **ERRORS},
    ),
    create=extend_schema(
        summary="Create a listing",
        request=ListingSerializer,
        responses={201: ListingSerializer, **ERRORS},
        examples=[LISTING_EXAMPLE],
    ),
    retrieve=extend_schema(
        summary="Retrieve a listing",
        responses={200: ListingSerializer, **ERRORS},
    ),
    update=extend_schema(
        summary="Replace a listing",
        description="Full replacement: every writable field must be supplied.",
        request=ListingSerializer,
        responses={200: ListingSerializer, **ERRORS},
    ),
    partial_update=extend_schema(
        summary="Partially update a listing",
        request=ListingSerializer,
        responses={200: ListingSerializer, **ERRORS},
    ),
    destroy=extend_schema(
        summary="Delete a listing",
        responses={204: OpenApiResponse(description="Deleted; no body."), **ERRORS},
    ),
)
class ListingViewSet(viewsets.ModelViewSet):
    """Listings resource: full CRUD plus a filtered, distance-aware search.

    list:      GET    /api/listings/
    create:    POST   /api/listings/
    retrieve:  GET    /api/listings/{id}/
    update:    PUT    /api/listings/{id}/
    partial:   PATCH  /api/listings/{id}/
    destroy:   DELETE /api/listings/{id}/
    search:    GET    /api/listings/search/?type=rent&min_price=1000&lat=..&lng=..&radius_km=5
    """

    queryset = Listing.objects.all()
    serializer_class = ListingSerializer
    pagination_class = ListingPagination
    http_method_names = ["get", "post", "put", "patch", "delete", "head", "options"]

    def get_serializer_class(self):
        return SearchResultSerializer if self.action == "search" else ListingSerializer

    def list(self, request, *args, **kwargs):
        """Newest first. Use /search/ to filter."""
        queryset = self.filter_queryset(self.get_queryset())
        page = self.paginate_queryset(queryset)
        if page is not None:
            return self.get_paginated_response(self.get_serializer(page, many=True).data)
        return Response(self.get_serializer(queryset, many=True).data)

    @extend_schema(
        summary="Search listings",
        tags=["search"],
        description=(
            "Filters by type, price range and bedrooms, and optionally returns only "
            "listings within `radius_km` of a point. Distance results are ordered "
            "nearest first and each row carries `distance_km`. Invalid or "
            "incomplete parameters return a 400 listing every offending field."
        ),
        parameters=[SearchQuerySerializer],
        responses={200: SearchResultSerializer(many=True), **ERRORS},
    )
    @action(detail=False, methods=["get"])
    def search(self, request):
        """Search listings.

        Filters: `type`, `min_price`, `max_price`, `bedrooms`, `min_bedrooms`,
        `max_bedrooms` and the geo triple `lat` + `lng` + `radius_km`.
        Sorts by: `newest`, `price_asc`, `price_desc`, `bedrooms_desc`,
        `distance` (defaults to distance when lat/lng/radius are given,
        newest otherwise). Invalid parameters return a 400 with the error envelope.
        """
        params = SearchQuerySerializer(data=request.query_params)
        params.is_valid(raise_exception=True)
        data = params.validated_data

        queryset = apply_exact_bedrooms(apply_filters(self.get_queryset(), data), data)

        distances = {}
        if "radius_km" in data:
            queryset, distances = rank_by_distance(
                queryset, data["lat"], data["lng"], data["radius_km"]
            )
            default_sort = "distance"
        else:
            default_sort = "newest"

        queryset = order_queryset(queryset, data.get("sort", default_sort))
        page = self.paginate_queryset(queryset)
        if page is None:
            page = list(queryset)
        for listing in page:
            listing.distance_km = distances.get(listing.pk)

        return self.get_paginated_response(self.get_serializer(page, many=True).data)


@method_decorator(never_cache, name="dispatch")
@extend_schema(
    summary="Health check",
    tags=["health"],
    description="Liveness probe. Does not touch the database.",
    responses={200: OpenApiTypes.OBJECT},
)
class HealthView(APIView):
    """GET /api/health/ — liveness probe, no database round-trip."""

    authentication_classes: list = []
    permission_classes: list = []

    def get(self, request):
        return Response({"status": "ok"})
